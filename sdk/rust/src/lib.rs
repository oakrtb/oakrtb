//! - [`builder`]: fluent builders for strongly typed models
//! - [`view`]: strongly typed BidRequest/BidResponse query views
//! - [`bidcheck`]: bid-to-request auction constraint checks (separate from Schema and basic validation)
//! - [`proto`]: generated protobuf messages (`oakrtb.v2`)

pub mod bidcheck;
pub mod builder;
pub mod codec;
#[cfg(feature = "jsonschema")]
pub mod jsonschema;
mod model_json;
pub mod validation;
